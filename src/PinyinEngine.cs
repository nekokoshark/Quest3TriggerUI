    // Self-contained pinyin input engine — the VR-side Chinese IME.
    //
    // Why not the desktop IME? We tried bridging IMM32: composition text is
    // exposed to legacy apps through CUAS, but modern TSF IMEs (Microsoft
    // Pinyin) never populate ImmGetCandidateList for unaware apps — the
    // candidate data simply isn't readable. Routing letters through
    // keybd_event also breaks whenever the desktop window isn't foreground.
    // A built-in engine has neither dependency and behaves identically
    // regardless of which IME the desktop happens to use.
    //
    // Data files (generated by 工作区2/PinyinEngine/build_dict.py from
    // rime-pinyin-simp + phrase-pinyin-data + rime-terra-pinyin):
    //   pinyin_dict.txt      letters<TAB>word word ...   (exact keys)
    //   pinyin_initials.txt  initials<TAB>word word ...  (简拼 shorthand)
    //   pinyin_fuzzy.txt     normletters<TAB>word ...    (模糊音 keys)
    //   pinyin_syllables.txt syllable per line           (segmentation set)
    internal static class PinyinEngine
    {
        internal enum KeyResult { NotHandled, Consumed, CommitText }

        private const int PageSize = 9;
        private const int MaxCandidates = 400;
        private const int MaxSegPaths = 64;
        private const int MaxInputLen = 40;

        private static bool _enabled = true;
        private static string _comp = string.Empty;
        private static int _pageStart;
        private static int _nextSeq;
        private static readonly List<Cand> _cands = new List<Cand>();
        private static readonly ImeCandidateSnapshot _snapshot =
            new ImeCandidateSnapshot();

        // Cloud-first candidate tier — Baidu search-suggestion API, queried on
        // a background thread per composition change. It maps pinyin (full or
        // 简拼) to the words people actually search — modern terms like
        // 雷电将军 land first. Cloud words insert at the top of the local
        // candidate list; on failure (offline, timeout, empty result) the
        // engine backs off for CloudCooldownMs and the local dictionary
        // carries the session alone.
        internal static bool CloudEnabled = true;
        private const int CloudTimeoutMs = 2000;
        private const int CloudCooldownMs = 15000;
        private const int CloudMinLetters = 3;
        private const int CloudMaxInFlight = 3;
        private static string _cloudLastQuery;
        private static int _cloudInFlight;
        private static int _cloudDownUntil;      // Environment.TickCount
        private static bool _cloudFailLogged;
        private static bool _cloudTlsReady;
        private static readonly object _cloudGate = new object();
        private static readonly Queue<CloudResult> _cloudDone =
            new Queue<CloudResult>();

