        }

        private static Dictionary<string, string[]> _full;
        private static Dictionary<string, string[]> _initials;
        private static Dictionary<string, string[]> _fuzzy;
        private static HashSet<string> _syllables;
        private static string[] _allKeys;

        // ---- user dictionary (learning) -----------------------------------
        // Committed words are remembered under both their full-syllable key
        // and their initials key, so a phrase typed once in full pinyin is
        // later reachable via 简拼 too. Persisted to a small txt next to the
        // dictionaries; writes are coalesced on a background thread.
        internal static bool UserLearning = true;
        private const string UserFileName = "Quest3TriggerUI.pinyin-user.txt";
        private const int MaxUserPerKey = 12;
        private static Dictionary<string, List<UEntry>> _userFull;
        private static Dictionary<string, List<UEntry>> _userInit;
        private static bool _userDirty;
        private static bool _userSaveQueued;
        // Accumulates the syllables+text of consecutive commits within one
        // composition — when the composition empties, the whole phrase is
        // learned as a unit (桌面输入法的组词记忆).
        private static readonly List<string> _sessionSyls =
            new List<string>();
        private static readonly System.Text.StringBuilder _sessionText =
            new System.Text.StringBuilder();

        private sealed class UEntry
        {
            internal string Word;
            internal int Count;
            internal string InitKey;   // "" for single-syllable words
        }
        private static bool _loadStarted;

        private sealed class Cand
        {
            internal string Word;
            internal int Consume;   // raw letters this word covers
            internal int Rank;      // -2 cloud,0 exact-full,1 fuzzy-full,2 completion,3 exact-partial,4 fuzzy-partial,5 initials
            internal int Cover;     // syllables/letters covered — tiebreak inside a rank
            internal int Seq;       // insertion order = weight order within bucket
        }

        private sealed class Seg
        {
            internal readonly List<string> Syls = new List<string>();
            internal string Partial = string.Empty;
        }

